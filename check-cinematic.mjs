import fs from 'node:fs/promises';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const source=await fs.readFile('index.html','utf8');
const built=await fs.readFile('dist/index.html','utf8');
const script=source.match(/<script>([\s\S]*?)<\/script>/)?.[1];
assert.ok(script,'Inline native JavaScript is present');
new vm.Script(script);
const elements=new Map();
const makeElement=id=>({id,value:'',min:'',max:'',textContent:'',dataset:{},attributes:{},listeners:{},style:{setProperty(k,v){this[k]=v}},classList:{values:new Set(),add(...v){v.forEach(x=>this.values.add(x))},remove(...v){v.forEach(x=>this.values.delete(x))},toggle(v,on){on?this.values.add(v):this.values.delete(v)}},addEventListener(type,fn){this.listeners[type]=fn},setAttribute(k,v){this.attributes[k]=v},setCustomValidity(v){this.validation=v},checkValidity(){return true},scrollIntoView(){this.scrolled=true},click(){this.clicked=true}});
for(const m of source.matchAll(/\bid="([^"]+)"/g)){assert.ok(!elements.has(m[1]),'Unique element ID: '+m[1]);elements.set(m[1],makeElement(m[1]));}
for(const m of source.matchAll(/<input\b[^>]*\bid="([^"]+)"[^>]*>/g)){const el=elements.get(m[1]);for(const prop of ['value','min','max'])el[prop]=m[0].match(new RegExp('\\b'+prop+'="([^"]*)"'))?.[1]||'';}
for(const m of source.matchAll(/href="#([^"]+)"/g))assert.ok(elements.has(m[1]),'Anchor target exists: '+m[1]);
assert.ok(!built.includes('@@'),'No unresolved media placeholders');
assert.ok(!/<script[^>]+src=/.test(built),'No remote JavaScript');
assert.ok(!/<(?:img|link)[^>]+(?:src|href)="https?:/.test(built),'No external asset dependency');
assert.equal((built.match(/data:image\/png;base64,/g)||[]).length,3,'Three embedded campaign assets');
assert.equal((built.match(/data:font\/woff2;base64,/g)||[]).length,2,'Two embedded font families');
const diagramNodes=['traffic','agent','crm','cash'].map(node=>Object.assign(makeElement(node),{dataset:{node}}));
const registered=[];
const ctx=vm.createContext({console,Intl,Date,Math,Number,Object,Error,JSON,Blob,URL,AbortController,setTimeout:()=>0,document:{getElementById:id=>{assert.ok(elements.has(id),'Missing DOM element '+id);return elements.get(id)},querySelectorAll:selector=>selector==='.diagram-node'?diagramNodes:[],createElement:tag=>makeElement(tag),modelContext:{registerTool(tool){registered.push(tool)}}},window:{addEventListener(){}}});
vm.runInContext(script,ctx);
const calculate=vm.runInContext('calculateModel',ctx);
const base={spend:500000,lag:10,cpl:1000,close:10,margin:5000};
const r=calculate(base);
assert.equal(r.burn,400000);
assert.equal(r.leads,500);
assert.ok(r.recovered>194000&&r.recovered<195000);
assert.equal(calculate({...base,lag:0}).recovered,0,'Instant human response has no incremental recovery');
assert.equal(calculate({...base,close:0}).recovered,0);
assert.equal(calculate({...base,margin:0}).recovered,0);
assert.ok(calculate({...base,lag:60}).burn>499000);
assert.ok(calculate({...base,spend:10000000}).recovered>r.recovered);
assert.throws(()=>calculate({...base,cpl:0}));
assert.throws(()=>calculate({...base,spend:99999}));
assert.throws(()=>calculate({...base,lag:NaN}));
vm.runInContext("inspectNode('cash')",ctx);
assert.equal(elements.get('node-title').textContent,'Close the measurement loop.');
assert.equal(diagramNodes[3].attributes['aria-pressed'],'true');
assert.throws(()=>vm.runInContext("inspectNode('missing')",ctx));
assert.equal(registered.length,1);
assert.equal(registered[0].name,'model_revenue_response_scenario');
assert.equal(registered[0].annotations.readOnlyHint,false);
const modeled=await registered[0].execute({spend:1000000,lag:20});
assert.equal(modeled.illustrative,true);
assert.equal(elements.get('spend').value,1000000);
const before=elements.get('spend').value;
await assert.rejects(()=>registered[0].execute({spend:-1,lag:20}));
assert.equal(elements.get('spend').value,before,'Invalid tool input must preserve state');
elements.get('cpl').value='';
vm.runInContext('updateModel()',ctx);
assert.equal(elements.get('recovered-value').textContent,'—','Blank assumptions do not show stale estimates');
elements.get('cpl').value='1000';
elements.get('organization').value='Example Enterprise';
elements.get('email').value='team@example.com';
elements.get('mission').value='Connect intake and CRM';
elements.get('booking-spend').value='₹5–25 lakh';
elements.get('focus').value='Intake & response speed';
elements.get('booking-form').listeners.submit({preventDefault(){}});
assert.equal(vm.runInContext('currentBrief.status',ctx),'local_draft_not_submitted');
assert.equal(vm.runInContext('currentBrief.organization',ctx),'Example Enterprise');
elements.get('booking-form').listeners.input();
assert.equal(vm.runInContext('currentBrief',ctx),null,'Edits invalidate the previous brief');
console.log('PASS: inline JS syntax, anchors, embedded assets, model boundaries, invalid inputs, blueprint state, local brief lifecycle, and mocked WebMCP contract.');
console.log('Live browser WebMCP verification and visual browser QA were not performed.');
